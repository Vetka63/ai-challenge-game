        public static Texture2D Create(bool bold = false)
        {
            var texture = new Texture2D(96, 48, TextureFormat.RGBA32, false) { name = "Original ASCII glyph atlas", filterMode = FilterMode.Point, wrapMode = TextureWrapMode.Clamp };
            var pixels = new Color32[96 * 48];
            for (int code = 32; code < 128; code++)
            {
                char glyph = char.ToUpperInvariant((char)code);
                if (!Patterns.TryGetValue(glyph, out string pattern)) continue;
                var rows = pattern.Split('/');
                int x = (code - 32) % 16 * 6, y = (code - 32) / 16 * 8;
                for (int row = 0; row < 7; row++)
                    for (int col = 0; col < 5; col++)
                        if (rows[row][col] == '1')
                        {
                            int extentX = bold ? 2 : 1;
                            int extentY = bold && glyph != '*' && glyph != ':' && glyph != '=' ? 2 : 1;
                            for (int dx = 0; dx < extentX; dx++) for (int dy = 0; dy < extentY; dy++)
                                pixels[(y + 7 - row - dy) * 96 + x + col + dx] = new Color32(255, 255, 255, 255);
                        }
            }
            texture.SetPixels32(pixels); texture.Apply();
            return texture;
        }
