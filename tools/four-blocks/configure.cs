var scene = UnityEditor.SceneManagement.EditorSceneManager.OpenScene("Assets/Scenes/Arena.unity");
var camera = UnityEngine.Camera.main;
if(camera==null) throw new System.Exception("Arena camera missing");
var pipeline = UnityEngine.Rendering.GraphicsSettings.currentRenderPipeline;
if(pipeline==null || !pipeline.GetType().FullName.Contains("Universal")) throw new System.Exception("URP required");
var pp=camera.GetComponent<UnityEngine.Rendering.Universal.PixelPerfectCamera>() ?? camera.gameObject.AddComponent<UnityEngine.Rendering.Universal.PixelPerfectCamera>();
pp.assetsPPU=40; pp.refResolutionX=1280; pp.refResolutionY=720;
pp.gridSnapping=UnityEngine.Rendering.Universal.PixelPerfectCamera.GridSnapping.PixelSnapping;
pp.cropFrame=UnityEngine.Rendering.Universal.PixelPerfectCamera.CropFrame.None;
camera.orthographic=true;camera.orthographicSize=9;
camera.allowHDR=false;camera.allowMSAA=false;camera.allowDynamicResolution=false;
camera.backgroundColor=new UnityEngine.Color(.025f,.04f,.06f);
var data=camera.GetComponent<UnityEngine.Rendering.Universal.UniversalAdditionalCameraData>();
data.renderPostProcessing=false;data.antialiasing=UnityEngine.Rendering.Universal.AntialiasingMode.None;
UnityEngine.QualitySettings.antiAliasing=0;UnityEngine.QualitySettings.vSyncCount=0;
var settings=UnityEditor.AssetDatabase.LoadAssetAtPath<AsciiArena.ArenaSettings>("Assets/Prototype/Data/ArenaSettings.asset");
settings.initialEnemies=12;settings.spawnPerSecond=1.4f;settings.crowdLimit=140;
settings.runDuration=600;settings.bossAt=540;settings.eliteInterval=180;
settings.finalSpawnMultiplier=3.5f;settings.bossHealth=1800;
settings.contactDamage=7;settings.enemyShotDamage=8;
settings.firstLevelExperience=12;settings.experiencePerLevel=8;settings.pickupRadius=2.8f;
UnityEditor.EditorUtility.SetDirty(settings);
if(UnityEngine.Object.FindFirstObjectByType<AsciiArena.ArenaAudio>()==null)new UnityEngine.GameObject("ASCII sound cues").AddComponent<AsciiArena.ArenaAudio>();
if(camera.GetComponent<UnityEngine.AudioListener>()==null)camera.gameObject.AddComponent<UnityEngine.AudioListener>();
UnityEditor.PlayerSettings.defaultScreenWidth=1280;UnityEditor.PlayerSettings.defaultScreenHeight=720;
UnityEditor.PlayerSettings.fullScreenMode=UnityEngine.FullScreenMode.Windowed;
UnityEditor.PlayerSettings.runInBackground=true;
UnityEditor.PlayerSettings.SetUseDefaultGraphicsAPIs(UnityEditor.BuildTarget.StandaloneWindows64,false);
UnityEditor.PlayerSettings.SetGraphicsAPIs(UnityEditor.BuildTarget.StandaloneWindows64,new[]{UnityEngine.Rendering.GraphicsDeviceType.Direct3D11});
UnityEditor.EditorUtility.SetDirty(camera);
UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(scene);
UnityEditor.SceneManagement.EditorSceneManager.SaveScene(scene);
UnityEditor.AssetDatabase.SaveAssets();
return new {scene=scene.path,objects=scene.GetRootGameObjects().Select(g=>g.name).ToArray(),camera=camera.orthographicSize,ppu=pp.assetsPPU,runDuration=settings.runDuration};
